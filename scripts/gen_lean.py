#!/usr/bin/env python3
"""Generate one Lean module per model in the Lean side's scope: Bench/<id>.lean.

The module reads the model with Tamalean's `.spthy` reader and states one `certify` per lemma
of the file, through the harness's commands (Bench/Harness.lean):

  import Bench.Harness
  bench_model "../../models/<id>/<file>.spthy"        -- tamarin_theory_file, timed
  bench_certify "lemma" «Theory».Lemmas.«lemma»       -- example : … := by certify, timed

Models of observational equivalence (diff models) are out of the Lean side's scope.  Nothing
imports the generated modules (Bench.lean imports the harness only), so one that fails never
breaks `lake build`; scripts/run_lean.py runs each one on its own.

  python3 -I scripts/gen_lean.py           # write every module (and remove stale ones)
  python3 -I scripts/gen_lean.py --check   # fail if a module differs from what this writes
"""

import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # -I leaves the script's dir out
import benchlib  # noqa: E402


def strip_comments(text):
    """The text without `//` and (nested) `/* */` comments; strings are kept as they are."""
    out, i, n, depth, in_str = [], 0, len(text), 0, False
    while i < n:
        c = text[i]
        two = text[i:i + 2]
        if depth:
            if two == "/*":
                depth += 1
                i += 2
            elif two == "*/":
                depth -= 1
                i += 2
            else:
                if c == "\n":
                    out.append(c)
                i += 1
            continue
        if in_str:
            out.append(c)
            if c == '"':
                in_str = False
            i += 1
            continue
        if c == '"':
            in_str = True
            out.append(c)
            i += 1
        elif two == "/*":
            depth = 1
            i += 2
        elif two == "//":
            j = text.find("\n", i)
            i = n if j < 0 else j
        else:
            out.append(c)
            i += 1
    return "".join(out)


THEORY_RE = re.compile(r"\btheory\s+([A-Za-z0-9_]+)")
LEMMA_RE = re.compile(r"(?m)^\s*lemma\s+([A-Za-z0-9_]+)\s*(?:\[[^\]]*\])?\s*:")


def theory_and_lemmas(text):
    t = strip_comments(text)
    # lemma formulas are strings: drop their contents so that nothing in them looks like an item
    t = re.sub(r'"[^"]*"', '""', t)
    m = THEORY_RE.search(t)
    return (m.group(1) if m else None), LEMMA_RE.findall(t)


def lean_name(s):
    return "«" + s + "»"


def module_path(model_id):
    return benchlib.BENCH / f"{model_id}.lean"


def render(s, x):
    mp = benchlib.model_path(s, x)
    mod = module_path(x["id"])
    rel = os.path.relpath(mp, mod.parent)
    text = mp.read_text(encoding="utf-8", errors="replace")
    thy, lemmas = theory_and_lemmas(text)
    where = "models" if x["redistributable"] else "cache"
    lines = [
        "import Bench.Harness",
        "",
        "/-!",
        f"# `{x['id']}`",
        "",
        f"The model `{where}/{x['id']}/{benchlib.model_entry(x)['dest']}`, read by Tamalean's "
        "`.spthy` reader, and one",
        "`certify` per lemma.  Generated by `scripts/gen_lean.py` from `models/manifest.toml`; "
        "do not edit.",
        "-/",
        "",
        "set_option maxHeartbeats 0",
        "",
        f'bench_model "{rel}"',
    ]
    if thy and lemmas:
        lines.append("")
        for lem in lemmas:
            lines.append(f'bench_certify "{lem}" {lean_name(thy)}.Lemmas.{lean_name(lem)}')
    return "\n".join(lines) + "\n", lemmas


def generate(check=False, only=None):
    m = benchlib.load_manifest()
    want = {}
    for s, x in benchlib.iter_models(m):
        if not benchlib.lean_in_scope(x):
            continue
        if only and not x["id"].startswith(only):
            continue
        if not benchlib.model_path(s, x).exists():
            print(f"skipped {x['id']}: the model file is missing (scripts/fetch_models.py)",
                  file=sys.stderr)
            continue
        want[module_path(x["id"])] = render(s, x)[0]
    stale = 0
    for p, text in want.items():
        old = p.read_text(encoding="utf-8") if p.exists() else None
        if old != text:
            stale += 1
            if check:
                print(f"stale: {p.relative_to(benchlib.ROOT)}", file=sys.stderr)
            else:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(text, encoding="utf-8")
    removed = 0
    if not only:
        keep = set(want) | {benchlib.BENCH / "Harness.lean"}
        for p in benchlib.BENCH.rglob("*.lean"):
            if p not in keep:
                removed += 1
                if not check:
                    p.unlink()
    print(f"{len(want)} modules, {stale} {'stale' if check else 'written'}, "
          f"{removed} {'extra' if check else 'removed'}", file=sys.stderr)
    return 0 if not check or (stale == 0 and removed == 0) else 1


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--only")
    a = ap.parse_args()
    sys.exit(generate(a.check, a.only))


if __name__ == "__main__":
    main()
