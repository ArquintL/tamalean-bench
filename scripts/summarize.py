#!/usr/bin/env python3
"""Write results/summary.md from the manifest and the results under results/.

Per source and overall: the counts of Tamarin's verdicts and of Tamalean's outcomes, and why
Tamalean's reader rejected the models it rejected; then a table per lemma for the models of the
papers the benchmark runs first.  Each tool's results say which guidance setting they belong to
(see the README); the tables put them side by side, and a comparison is only meaningful within
one setting.

  python3 -I scripts/summarize.py
"""

import collections
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # -I leaves the script's dir out
import benchlib  # noqa: E402
import run_tamarin  # noqa: E402

TAMARIN_ORDER = ["verified", "falsified", "incomplete", "timeout", "memory limit", "error",
                 "not run"]
LEAN_ORDER = ["proved", "attack found", "no trace", "no verdict", "timeout", "rejected",
              "no statement", "not run"]


def fmt_time(v):
    if v is None:
        return ""
    return f"{v:.1f}" if v >= 1 else f"{v:.2f}"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |")
    return out


def main():
    m = benchlib.load_manifest()
    lines = ["# Results", "",
             "Generated by `scripts/summarize.py` from `models/manifest.toml`, `results/tamarin/` "
             "and `results/tamalean/`.  Tamarin's verdicts are its own, per lemma, with the model's "
             "flags and oracle (the setting \"a ranking\" when the model has an oracle, a heuristic "
             "or a tactic, \"no guidance\" otherwise); Tamalean's outcomes are those of `certify` "
             "with the model's default sources (\"no guidance\").  Results are comparable only "
             "within one setting.", ""]

    per_source = collections.OrderedDict()
    reasons = collections.Counter()
    reasons_by_source = collections.defaultdict(collections.Counter)
    overall = {"models": 0, "tam_run": 0, "tam_loaded": 0, "tam": collections.Counter(),
               "lean_scope": 0, "lean_run": 0, "lean_ok": 0, "lean": collections.Counter()}
    for s, x in benchlib.iter_models(m):
        k = s["slug"]
        d = per_source.setdefault(k, {"models": 0, "tam_run": 0, "tam_loaded": 0,
                                      "tam": collections.Counter(), "lean_scope": 0,
                                      "lean_run": 0, "lean_ok": 0, "lean": collections.Counter()})
        for agg in (d, overall):
            agg["models"] += 1
        r = benchlib.load_result("tamarin", x["id"])
        if r:
            for agg in (d, overall):
                agg["tam_run"] += 1
                if r.get("load", {}).get("status") == "ok":
                    agg["tam_loaded"] += 1
                for l in r.get("lemmas", []):
                    agg["tam"][l["verdict"]] += 1
        if benchlib.lean_in_scope(x):
            for agg in (d, overall):
                agg["lean_scope"] += 1
            q = benchlib.load_result("tamalean", x["id"])
            if q:
                for agg in (d, overall):
                    agg["lean_run"] += 1
                    if q.get("reader", {}).get("ok"):
                        agg["lean_ok"] += 1
                    for l in q.get("lemmas", []):
                        agg["lean"][l["outcome"]] += 1
                if not q.get("reader", {}).get("ok"):
                    why = q.get("reader", {}).get("reason", "unknown")
                    reasons[why] += 1
                    reasons_by_source[k][why] += 1

    def counts(c, order):
        keys = [o for o in order if c.get(o)] + sorted(set(c) - set(order))
        return ", ".join(f"{c[o]} {o}" for o in keys) or "-"

    lines += ["## Per source", ""]
    rows = []
    for k, d in list(per_source.items()) + [("**all**", overall)]:
        rows.append([k, d["models"], f"{d['tam_run']} ({d['tam_loaded']} loaded)",
                     counts(d["tam"], TAMARIN_ORDER), d["lean_scope"],
                     f"{d['lean_run']} ({d['lean_ok']} read)", counts(d["lean"], LEAN_ORDER)])
    lines += table(["source", "models", "Tamarin: models run", "Tamarin: lemmas",
                    "Lean: models in scope", "Lean: models run (read by the reader)",
                    "Lean: lemmas"], rows)
    alone = shared = 0
    loads = []
    for s_, x_ in benchlib.iter_models(m):
        q = benchlib.load_result("tamalean", x_["id"]) if benchlib.lean_in_scope(x_) else None
        for l in (q or {}).get("lemmas", []):
            if l.get("outcome") in ("proved", "attack found", "no trace", "no verdict", "timeout"):
                if l.get("measured_alone"):
                    alone += 1
                else:
                    shared += 1
        r_ = benchlib.load_result("tamarin", x_["id"])
        for l in (r_ or {}).get("lemmas", []):
            if l.get("load_avg") is not None:
                loads.append(l["load_avg"])
    lines += ["", "Tamarin's lemmas count each side of an observational-equivalence model "
              "separately.  The Lean side leaves observational equivalence (diff models) out.", ""]
    lines += [f"Timing: Tamarin ran on a machine shared with other work, two lemmas at a time, each "
              f"with `+RTS -N4 -M8G` (the load average when its lemmas ended: median "
              f"{sorted(loads)[len(loads) // 2] if loads else '-'}, highest "
              f"{max(loads) if loads else '-'}); each result records it.  Of Tamalean's lemma times, "
              f"{alone} were measured with the machine to itself and {shared} on the shared "
              "machine (each lemma says which, `measured_alone`): the lemmas that ended with a "
              "verdict are timed again alone.", ""]

    lines += ["## Why Tamalean's reader rejected a model", "",
              "The first construct the reader does not accept, by number of models:", ""]
    lines += table(["reason", "models"], [[k, v] for k, v in reasons.most_common()])
    lines.append("")
    lines += ["Per source:", ""]
    rows = []
    for k, c in reasons_by_source.items():
        rows.append([k, "; ".join(f"{v} {r}" for r, v in c.most_common())])
    lines += table(["source", "reasons"], rows)
    lines.append("")

    lines += ["## The papers run first, per lemma", ""]
    for name, papers in run_tamarin.GROUPS:
        group = [(s, x) for s, x in benchlib.iter_models(m) if set(x.get("paper", [])) & papers]
        if not group:
            continue
        lines += [f"### {name}", ""]
        rows = []
        for s, x in group:
            r = benchlib.load_result("tamarin", x["id"])
            q = benchlib.load_result("tamalean", x["id"]) if benchlib.lean_in_scope(x) else None
            tl = {}
            if r:
                for l in r.get("lemmas", []):
                    tl.setdefault(l["name"], []).append(l)
            ql = {l["name"]: l for l in (q or {}).get("lemmas", [])}
            names = list(dict.fromkeys(list(tl) + list(ql)))
            if not names:
                status = "not run yet" if not r else (
                    "Tamarin did not load it: " + r.get("load", {}).get("message", "")[:120])
                rows.append([x["id"], "", status, "", "", "", ""])
                continue
            for n in names:
                ts = tl.get(n, [])
                tv = ", ".join(l["verdict"] + (f" [{l['side']}]" if l.get("side") else "")
                               for l in ts)
                tt = ", ".join(fmt_time(l.get("wall_s")) for l in ts)
                st = ", ".join(str(l.get("steps") or "") for l in ts)
                ql_ = ql.get(n)
                if not benchlib.lean_in_scope(x):
                    lv, lt = "out of scope", ""
                elif q is None:
                    lv, lt = "not run yet", ""
                elif not q.get("reader", {}).get("ok"):
                    lv, lt = "rejected: " + q["reader"].get("reason", ""), ""
                elif ql_:
                    lv = ql_["outcome"]
                    lt = fmt_time(ql_["ms"] / 1000) if ql_.get("ms") is not None else ""
                else:
                    lv, lt = "", ""
                rows.append([x["id"], n, tv, st, tt, lv, lt])
        lines += table(["model", "lemma", "Tamarin", "steps", "Tamarin s", "Tamalean",
                        "Tamalean s"], rows)
        lines.append("")
    lt = benchlib.RESULTS / "tamarin" / "long-runs.txt"
    if lt.exists():
        n = sum(1 for ln in lt.read_text().splitlines() if ln and not ln.startswith("#"))
        lines += [f"`results/tamarin/long-runs.txt` lists {n} lemmas or models that reached a "
                  "limit here.", ""]
    out = benchlib.RESULTS / "summary.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out.relative_to(benchlib.ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
